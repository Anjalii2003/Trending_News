-- One-time provisioning of the News Engine's PostgreSQL footprint. Run by a DATABASE ADMIN (deploy/bootstrap_pg.py runs exactly
-- this, with generated passwords, and prints what it did). Idempotent. It creates ONLY:
--   schema  news_engine               the derived data (see scripts/lib/news_pgstore.py); owned by the engine role
--   role    news_engine_app           the engine: SELECT on the two source tables it reads, full rights on news_engine only
--   role    news_engine_reader        the dashboard: SELECT on news_engine only
-- Nothing in any existing schema is altered; no privilege is granted on any production table except SELECT on
-- tmc.article_label and tmc.taxonomy_node (labels + taxonomy the engine reads).
--
-- To undo everything:   DROP SCHEMA news_engine CASCADE;  DROP OWNED BY news_engine_app; DROP ROLE news_engine_app;
--                       DROP OWNED BY news_engine_reader; DROP ROLE news_engine_reader;

CREATE SCHEMA IF NOT EXISTS news_engine;

-- (each CREATE ROLE only if the role does not exist yet; passwords are generated by deploy/bootstrap_pg.py)
CREATE ROLE news_engine_app    LOGIN PASSWORD '<generated>' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION CONNECTION LIMIT 12;
CREATE ROLE news_engine_reader LOGIN PASSWORD '<generated>' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION CONNECTION LIMIT 12;

ALTER SCHEMA news_engine OWNER TO news_engine_app;
ALTER ROLE news_engine_app SET search_path = news_engine;
ALTER ROLE news_engine_reader SET search_path = news_engine;

GRANT CONNECT ON DATABASE <this database> TO news_engine_app, news_engine_reader;

-- source tables: read only
GRANT USAGE ON SCHEMA tmc TO news_engine_app;
GRANT SELECT ON tmc.article_label, tmc.taxonomy_node TO news_engine_app;
-- relevance reference (classifier ground truth): ids + domain columns only, never titles/content
GRANT SELECT (source_table, source_id, gt_domain_id) ON tmc.a0_ground_truth TO news_engine_app;

-- dashboard: read the derived schema only (including tables the engine creates later)
GRANT USAGE ON SCHEMA news_engine TO news_engine_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA news_engine TO news_engine_reader;
ALTER DEFAULT PRIVILEGES FOR ROLE news_engine_app IN SCHEMA news_engine GRANT SELECT ON TABLES TO news_engine_reader;
